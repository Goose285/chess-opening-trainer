// Phase 2: trap lines. Re-uses the engine-verified traps (tools/traps-src.mjs hand-made, tools/traps-mined.mjs mined) as drillable
// opening lines: you play the book moves, the opponent falls for the trap (weighted into the book like any other branch) and you play the
// refutation. Only traps whose solver colour matches the opening's colour are used; at most 3 per opening, hand-made first.
// Output: src/gambit-traps.js (TRAPLINES)
import fs from 'node:fs';
import { Chess } from 'chess.js';
import { OPENINGS } from '../src/openings.js';
import { TRAPS } from './traps-src.mjs';
import { MINED } from './traps-mined.mjs';
const MAX = 3;
const out = {};
for (const o of OPENINGS) {
  const mine = [...TRAPS.map((t) => ({ ...t, hand: 1 })), ...MINED].filter((t) => t.open === o.id);
  const use = [];
  for (const t of mine.sort((a, b) => (b.hand || 0) - (a.hand || 0) || a.rating - b.rating)) {
    const sans = t.line.split(' ');
    const solverWhite = (t.setup + 1) % 2 === 0; // index of the solver's first move; even index = white
    if ((o.side === 'white') !== solverWhite) continue;
    const g = new Chess(); try { sans.forEach((s) => g.move(s)); } catch { continue; }
    if (o.lines.some((l) => !l.extra && l.moves === t.line)) continue;
    let nm = `Trap: ${t.name.replace(/^.*? trap: /, '')}`; for (let k = 2; use.some((u) => u.name === nm) || o.lines.some((l) => !l.extra && l.name === nm); k++) nm = nm.replace(/ \(\d+\)$/, '') + ` (${k})`;
    use.push({ name: nm, moves: t.line, extra: 'trap', trap: true, idea: t.note });
    if (use.length >= MAX) break;
  }
  if (use.length) out[o.id] = use;
}
fs.writeFileSync(new URL('../src/gambit-traps.js', import.meta.url), `// GENERATED by tools/gen-trap-lines.mjs from the verified traps (tools/traps-src.mjs, tools/traps-mined.mjs): trap lines you can drill.
// The opponent walks into the trap, you play the refutation and win material. Marked trap:true so they are only ever in the book
// when the opponent is the one falling for it. Plain data: edit freely.
export const TRAPLINES = ${JSON.stringify(out, null, 1)};
`);
console.log(Object.entries(out).map(([k, v]) => `${k}:${v.length}`).join(' '), Object.values(out).flat().length);
