// Generates css/pieces.css: one rule per (piece set, colour, role). The active set is chosen by <html data-pieces="...">
// (src/themes.js). the default set (DEFAULT_PIECES) is also emitted without the attribute as the no-JS / first-paint default.
import fs from 'fs';
import { PIECE_SETS, DEFAULT_PIECES } from '../src/themes-data.js';
const ROLES = { pawn: 'P', knight: 'N', bishop: 'B', rook: 'R', queen: 'Q', king: 'K' };
let out = '/* GENERATED by tools/gen-piece-css.mjs - do not edit. Piece artwork lives in ../pieces/<set>/ (licences: THIRD_PARTY/PIECE-SET-CREDITS.md). */\n';
const rule = (sel, set, c, r) => `${sel} piece.${r}.${c === 'w' ? 'white' : 'black'} { --pimg: url('../pieces/${set}/${c}${ROLES[r]}.svg'); }\n`;
for (const c of ['w', 'b']) for (const r of Object.keys(ROLES)) out += rule('.cg-wrap', DEFAULT_PIECES, c, r);
for (const s of PIECE_SETS) for (const c of ['w', 'b']) for (const r of Object.keys(ROLES)) out += rule(`html[data-pieces="${s.id}"] .cg-wrap`, s.id, c, r);
fs.writeFileSync(new URL('../css/pieces.css', import.meta.url), out);
console.log('css/pieces.css', out.length, 'bytes');
