// Regenerates src/ease-data.js from the book + meta. Usage: node tools/gen-ease.mjs
import { writeFileSync } from 'node:fs';
import { OPENINGS } from '../src/openings.js';
import { META, STYLE } from '../src/meta.js';
import { buildBook } from '../src/book.js';
import { computeEase } from '../src/difficulty.js';
const t = computeEase(OPENINGS, buildBook, META, STYLE);
const rows = OPENINGS.map((o) => `  '${o.id}': { ease: '${t[o.id].ease}', score: ${t[o.id].score}, why: ${JSON.stringify(t[o.id].why)} },`);
writeFileSync(new URL('../src/ease-data.js', import.meta.url), `// GENERATED by tools/gen-ease.mjs from src/difficulty.js; do not edit by hand (re-run the generator after changing the book or meta).\nexport const EASE = {\n${rows.join('\n')}\n};\n`);
const by = (k) => OPENINGS.filter((o) => t[o.id].ease === k).map((o) => o.id);
console.log('easy', by('easy').length, by('easy').join(', ')); console.log('medium', by('medium').length); console.log('hard', by('hard').length, by('hard').join(', '));
