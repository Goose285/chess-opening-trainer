// Turns the Stockfish-mined candidates (tools/mine-traps.mjs -> /workspace/lichess/traps/<id>.json) into tools/traps-mined.mjs:
// up to N traps per gambit, mates first, distinct positions / distinct refutations. Run after mining:
//   node tools/curate-traps.mjs [dir ...]   (default: /workspace/lichess/traps and /workspace/lichess/traps2)
import fs from 'node:fs';
import { Chess } from 'chess.js';
import { OPENINGS } from '../src/openings.js';
import { TRAPS } from './traps-src.mjs';
import { MINED } from './traps-mined.mjs';
import { startEngine, verifyTrap } from './lib-engine.mjs';
const eng = startEngine();
const dirs = process.argv.length > 2 ? process.argv.slice(2) : ['/workspace/lichess/traps', '/workspace/lichess/traps2'];
const WANT = { danish: 5, fajarowicz: 5, traxler: 4 }; const DEF = 3;
const out = []; let rejected = 0;
const pieceName = (g) => (g >= 8 ? 'the queen' : g >= 5 ? 'a rook' : g >= 3 ? 'a piece' : g >= 2 ? 'two pawns' : 'a pawn');
const ONLY = process.env.ONLY ? process.env.ONLY.split(',') : null; // ONLY=id,id : curate just these openings and keep the rest of traps-mined.mjs as it is
for (const o of OPENINGS.filter((x) => x.gambit && (!ONLY || ONLY.includes(x.id)))) {
  const files = dirs.map((d) => `${d}/${o.id}.json`).filter((f) => fs.existsSync(f) && fs.statSync(f).size > 2); if (!files.length) continue;
  const have = TRAPS.filter((t) => t.open === o.id).length;
  const want = Math.max(0, (WANT[o.id] || DEF) - have);
  const cand = files.flatMap((f) => JSON.parse(fs.readFileSync(f, 'utf8'))).sort((x, y) => (y.mate - x.mate) || (y.d12 - x.d12)).filter((c) => c.mate || c.gain >= 2 || c.d12 >= 400);
  const used = new Set(), perPrefix = {}, picked = [];
  const strong = (c) => c.mate || c.gain >= 3 || c.d12 >= 600;
  for (const [cap, tier] of [[1, 1], [2, 1], [1, 2], [2, 2], [3, 2]]) { // strongest traps first, one per position; relax only if the opening would be left short
    for (const c of cand) {
      if (tier === 1 && !strong(c)) continue;
      if (picked.length >= want) break;
      const first = c.pv.split(' ')[0];
      const k = c.prefix + '|' + c.oppMove; if (used.has(k)) continue;
      if ((perPrefix[c.prefix] || 0) >= cap) continue;
      const sansV = [...c.prefix.split(' ').filter(Boolean), c.oppMove, ...c.pv.split(' ')];
      const probs = await verifyTrap(eng, Chess, sansV, c.prefix.split(' ').filter(Boolean).length);
      used.add(k); if (probs.length) { rejected++; continue; }
      perPrefix[c.prefix] = (perPrefix[c.prefix] || 0) + 1; picked.push(c);
    }
  }
  picked.forEach((c, i) => {
    const sans = [...c.prefix.split(' ').filter(Boolean), c.oppMove, ...c.pv.split(' ')];
    const ply = c.prefix.split(' ').filter(Boolean).length; const n = Math.floor(ply / 2) + 1; const label = ply % 2 === 0 ? `${n}.${c.oppMove}` : `${n}...${c.oppMove}`;
    const nSolver = Math.ceil(c.pv.split(' ').length / 2); const first = c.pv.split(' ')[0];
    const mateN = c.mate ? nSolver : 0;
    const quiet = !/[x+#]/.test(first);
    const themes = c.mate ? `mateIn${Math.min(nSolver, 3)}${quiet ? '' : ' sacrifice'}` : (c.gain >= 3 ? 'hangingPiece' : 'sacrifice');
    const rating = Math.max(500, Math.min(1400, 600 + 150 * (nSolver - 1) + (c.mate ? 0 : 100) + (quiet ? 150 : 0)));
    const who = o.side === 'white' ? 'Black' : 'White';
    const note = c.mate
      ? `${who} just played ${label}, which looks natural. But ${first} starts a forced checkmate in ${mateN}!`
      : `${who} just played ${label}, which looks natural. But ${first} punishes it${c.gain >= 2 ? ` and wins ${pieceName(c.gain)}` : ' with a winning attack'} (engine: +${(Math.min(c.d12, 900) / 100).toFixed(1)}).`;
    out.push({ id: `T-${o.id}-${have + i + 1}`, open: o.id, name: `${o.name.split(':')[0].replace(/ Gambit$| Attack$/, '')} trap: ${label}?`, rating, themes, note, setup: ply, line: sans.join(' ') });
  });
}
const all = ONLY ? [...MINED.filter((t) => !ONLY.includes(t.open)), ...out] : out;
fs.writeFileSync(new URL('./traps-mined.mjs', import.meta.url), `// GENERATED by tools/curate-traps.mjs from Stockfish-mined candidates (tools/mine-traps.mjs): positions where a natural-looking\n// move by the opponent loses (depth-4 search is fine with it, depth-14 refutes it with a unique reply). Edit freely; verified again\n// by ENGINE=1 node tools/build-tactics.mjs.\nexport const MINED = ${JSON.stringify(all, null, 1)};\n`);
eng.quit(); console.log('rejected by the engine check:', rejected);
const by = {}; out.forEach((t) => (by[t.open] = (by[t.open] || 0) + 1)); console.log(out.length, JSON.stringify(by));
