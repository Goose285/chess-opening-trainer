// Phase 4: "What's the idea?" one-liners, one per line of every opening. Built from the opening's hand-written idea (lore-text.js)
// plus facts read off the final position of the line (material, development, king safety), so each line gets its own sentence.
// Trap lines use the trap's own note. Output: src/ideas.js (plain data: edit any sentence freely and it is kept? no - rerun overwrites).
//   node tools/gen-ideas.mjs
import fs from 'node:fs';
import { Chess } from 'chess.js';
import { OPENINGS } from '../src/openings.js';
import { LORE } from '../src/lore-text.js';

const VAL = { p: 1, n: 3, b: 3, r: 5, q: 9 };
const first = (t) => { // first sentence(s): keep adding sentences until the note is a useful length (and never split inside "3...Nd4!?")
  const parts = t.split(/(?<=[.!?])\s+(?=[A-Z])/); let o = parts[0];
  for (let i = 1; o.length < 90 && i < parts.length; i++) o += ' ' + parts[i];
  return o.length > 200 ? o.slice(0, 197).replace(/\s+\S*$/, '') + '…' : o;
};
const plural = (n, w) => `${n} ${w}${n === 1 ? '' : 's'}`;
function facts(sans, side) {
  const g = new Chess(); sans.forEach((s) => g.move(s));
  const bd = g.board().flat().filter(Boolean);
  const sum = (c) => bd.filter((p) => p.color === c && p.type !== 'k').reduce((n, p) => n + VAL[p.type], 0);
  const me = side === 'white' ? 'w' : 'b', op = me === 'w' ? 'b' : 'w';
  const diff = sum(me) - sum(op);
  // pieces off their start squares
  const home = { w: ['b1', 'g1', 'c1', 'f1'], b: ['b8', 'g8', 'c8', 'f8'] };
  const dev = (c) => home[c].filter((sq) => { const p = g.get(sq); return !p || p.color !== c || !['n', 'b'].includes(p.type); }).length;
  const castled = (c) => { const k = bd.find((p) => p.color === c && p.type === 'k'); return null; };
  const kingSq = (c) => { for (const r of g.board()) for (const p of r) if (p && p.type === 'k' && p.color === c) return p.square; };
  const cast = (c) => { const k = kingSq(c); return c === 'w' ? ['g1', 'c1', 'h1', 'b1'].includes(k) : ['g8', 'c8', 'h8', 'b8'].includes(k); };
  return { diff, devMe: dev(me), devOp: dev(op), castMe: cast(me), castOp: cast(op), mate: g.isCheckmate(), plies: sans.length, g };
}
const out = {};
for (const o of OPENINGS) {
  const plan = first((LORE[o.id] && LORE[o.id].idea) || o.blurb);
  out[o.id] = {};
  for (const l of o.lines) {
    if (l.idea) { out[o.id][l.name] = l.idea; continue; }
    const f = facts(l.moves.split(' '), o.side);
    const bits = [];
    if (f.mate) bits.push('the game ends in checkmate');
    else {
      const d = f.diff;
      bits.push(d === 0 ? 'material is level' : d > 0 ? `you are ${d >= 3 ? 'a piece' : plural(d, 'pawn')} up` : `you are ${d <= -3 ? 'a piece' : plural(-d, 'pawn')} down`);
      if (f.devMe !== f.devOp) bits.push(f.devMe > f.devOp ? `you have ${plural(f.devMe, 'minor piece')} developed to their ${f.devOp}` : `they have ${plural(f.devOp, 'minor piece')} developed to your ${f.devMe}`);
      if (f.castMe && !f.castOp) bits.push('your king is safe and theirs is still in the centre');
      else if (!f.castMe && f.castOp) bits.push('their king is tucked away and yours is still in the centre');
    }
    const reply = /^Reply /.test(l.name) ? 'The opponent deviates here, but the plan is the same. ' : '';
    out[o.id][l.name] = `${reply}${plan} In this line ${bits.join(', ')}.`.replace('. In this line', '. At the end of this line');
  }
}
fs.writeFileSync(new URL('../src/ideas.js', import.meta.url), `// GENERATED by tools/gen-ideas.mjs: the "What's the idea?" sentence for every line, by opening id and line name.
// (Trap lines carry their own note from the verified trap data.) Shown when you finish a line and on the last step of "Watch it first".
export const IDEAS = ${JSON.stringify(out, null, 1)};
export const ideaOf = (openingId, lineName) => (IDEAS[openingId] || {})[lineName] || null;
// A finished line can map to several names ("A / B"); use the first one that has an idea.
export const ideaForNames = (openingId, names) => String(names || '').split(' / ').map((n) => ideaOf(openingId, n)).find(Boolean) || null;
`);
console.log(Object.values(out).reduce((n, v) => n + Object.keys(v).length, 0), 'ideas');
